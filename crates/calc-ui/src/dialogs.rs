//! About, licenses and preferences windows.

use crate::app::App;
use crate::i18n::{tr, tr_args};
use crate::menu::MenuCommand;
use calc_config::SYSTEM_THEME;
use eframe::egui::{self, Align2, ComboBox, Context, ScrollArea, Vec2};

/// Releases page linked from About (PKG-012: no auto-updater).
const RELEASES: &str = concat!(env!("CARGO_PKG_REPOSITORY"), "/releases");

/// Separator choices offered in Preferences: (character, label).
const DECIMALS: [(char, &str); 2] = [('.', ". (period)"), (',', ", (comma)")];
const GROUPS: [(char, &str); 5] = [
    (',', ", (comma)"),
    ('.', ". (period)"),
    ('\u{a0}', "  (space)"),
    ('\'', "' (apostrophe)"),
    ('_', "_ (underscore)"),
];

fn sep_label(c: char) -> String {
    match c {
        '\u{a0}' | '\u{202f}' | ' ' => "space".into(),
        c => c.to_string(),
    }
}

impl App {
    pub(crate) fn about(&mut self, ctx: &Context) {
        let mut open = self.about_open;
        let mut show_licenses = false;
        egui::Window::new(tr("help-about"))
            .open(&mut open)
            .collapsible(false)
            .resizable(false)
            .anchor(Align2::CENTER_CENTER, Vec2::ZERO)
            .show(ctx, |ui| {
                ui.heading(tr("app-name"));
                ui.label(tr_args(
                    "about-version",
                    &[("version", env!("CARGO_PKG_VERSION").into())],
                ));
                ui.label(tr("about-description"));
                ui.label(tr("about-font"));
                ui.hyperlink_to(tr("about-releases"), RELEASES);
                if ui.button(tr("help-licenses")).clicked() {
                    show_licenses = true;
                }
            });
        self.about_open = open && !show_licenses;
        if show_licenses {
            self.licenses_open = true;
        }
    }

    /// Third-party licenses generated by `cargo about` (NFR-042).
    pub(crate) fn licenses_window(&mut self, ctx: &Context) {
        let mut open = self.licenses_open;
        let text = self.licenses;
        egui::Window::new(tr("licenses-title"))
            .open(&mut open)
            .collapsible(false)
            .default_size([360.0, 260.0])
            .anchor(Align2::CENTER_CENTER, Vec2::ZERO)
            .show(ctx, |ui| {
                // Only the visible lines are laid out: the text is several hundred KB.
                let lines: Vec<&str> = text.lines().collect();
                let row_h = ui.text_style_height(&egui::TextStyle::Small);
                ScrollArea::both().auto_shrink(false).show_rows(
                    ui,
                    row_h,
                    lines.len(),
                    |ui, rows| {
                        for line in &lines[rows] {
                            ui.add(egui::Label::new(egui::RichText::new(*line).small()).extend());
                        }
                    },
                );
            });
        self.licenses_open = open;
    }

    pub(crate) fn preferences(&mut self, ctx: &Context) {
        let mut open = self.prefs_open;
        let mut chosen = None;
        let themes = self.store.list();
        let name_of = |id: &str| {
            themes
                .iter()
                .find(|t| t.id == id)
                .map_or_else(|| id.to_string(), |t| t.name.clone())
        };
        let os = self.os_locale;
        egui::Window::new(tr("prefs-title"))
            .open(&mut open)
            .collapsible(false)
            .resizable(false)
            .anchor(Align2::CENTER_CENTER, Vec2::ZERO)
            .show(ctx, |ui| {
                let s = &mut self.settings;
                egui::Grid::new("prefs")
                    .num_columns(2)
                    .spacing([8.0, 6.0])
                    .show(ui, |ui| {
                        ui.label(tr("prefs-theme"));
                        let current = if s.theme == SYSTEM_THEME {
                            tr("themes-follow-system")
                        } else {
                            name_of(&s.theme)
                        };
                        ComboBox::from_id_salt("pref-theme")
                            .selected_text(current)
                            .show_ui(ui, |ui| {
                                if ui
                                    .selectable_label(
                                        s.theme == SYSTEM_THEME,
                                        tr("themes-follow-system"),
                                    )
                                    .clicked()
                                {
                                    chosen = Some(SYSTEM_THEME.to_string());
                                }
                                for t in &themes {
                                    if ui.selectable_label(s.theme == t.id, &t.name).clicked() {
                                        chosen = Some(t.id.clone());
                                    }
                                }
                            });
                        ui.end_row();
                        for (label, value, salt) in [
                            (tr("prefs-theme-light"), &mut s.theme_light, "pref-light"),
                            (tr("prefs-theme-dark"), &mut s.theme_dark, "pref-dark"),
                        ] {
                            ui.label(label);
                            let before = value.clone();
                            ComboBox::from_id_salt(salt)
                                .selected_text(name_of(value))
                                .show_ui(ui, |ui| {
                                    for t in &themes {
                                        ui.selectable_value(value, t.id.clone(), &t.name);
                                    }
                                });
                            if *value != before && s.theme == SYSTEM_THEME {
                                chosen = Some(SYSTEM_THEME.to_string());
                            }
                            ui.end_row();
                        }
                    });
                if ui
                    .checkbox(&mut s.follow_high_contrast, tr("prefs-high-contrast"))
                    .changed()
                {
                    chosen = Some(s.theme.clone());
                }
                ui.separator();
                ui.strong(tr("prefs-numbers"));
                egui::Grid::new("prefs-num")
                    .num_columns(2)
                    .spacing([8.0, 6.0])
                    .show(ui, |ui| {
                        for (label, value, choices, system, salt) in [
                            (
                                tr("prefs-decimal"),
                                &mut s.decimal_separator,
                                &DECIMALS[..],
                                os.decimal,
                                "pref-dec",
                            ),
                            (
                                tr("prefs-group"),
                                &mut s.group_separator,
                                &GROUPS[..],
                                os.group,
                                "pref-grp",
                            ),
                        ] {
                            ui.label(label);
                            let from_os =
                                tr_args("prefs-from-locale", &[("sep", sep_label(system).into())]);
                            let shown = match *value {
                                None => from_os.clone(),
                                Some(c) => choices
                                    .iter()
                                    .find(|(x, _)| *x == c)
                                    .map_or_else(|| c.to_string(), |(_, l)| l.to_string()),
                            };
                            ComboBox::from_id_salt(salt)
                                .selected_text(shown)
                                .show_ui(ui, |ui| {
                                    ui.selectable_value(value, None, from_os);
                                    for (ch, l) in choices {
                                        ui.selectable_value(value, Some(*ch), *l);
                                    }
                                });
                            ui.end_row();
                        }
                    });
                ui.checkbox(&mut s.copy_locale_decimal, tr("prefs-copy-locale"));
                ui.checkbox(&mut s.copy_grouping, tr("prefs-copy-grouping"));
                ui.separator();
                if ui.button(tr("prefs-open-folder")).clicked() {
                    crate::app::open_path(&calc_config::config_dir());
                }
            });
        self.prefs_open = open;
        if let Some(id) = chosen {
            self.command(ctx, MenuCommand::Theme(id));
        }
    }
}
